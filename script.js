function setupQuiz() {
  const area = document.getElementById("quizArea");

  let current = 0;
  let score = 0;

  const showQuestion = () => {
    if (current >= CONFIG.quiz.length) {
      area.innerHTML = `
        <div class="quiz-result">
          <h3>
            ${
              score === CONFIG.quiz.length
                ? "Suspiciously perfect. 👀"
                : "Close enough. 😂"
            }
          </h3>

          <p>
            You scored ${score}/${CONFIG.quiz.length},
            but the actual prize is that you know too much about me already.
          </p>

          <button class="primary-btn" id="quizPrizeBtn">
            Claim your prize →
          </button>
        </div>
      `;

      document
        .getElementById("quizPrizeBtn")
        .addEventListener("click", () => {
          document
            .getElementById("letter")
            .scrollIntoView({ behavior: "smooth" });
        });

      return;
    }

    const q = CONFIG.quiz[current];

    area.innerHTML = `
      <div class="quiz-question">
        ${current + 1}. ${escapeHtml(q.question)}
      </div>

      <div class="quiz-options">
        ${q.options
          .map(
            (opt, i) =>
              `<button class="quiz-option" data-answer="${i}">
                ${escapeHtml(opt)}
              </button>`
          )
          .join("")}
      </div>
    `;

    area.querySelectorAll(".quiz-option").forEach((btn) => {
      btn.addEventListener("click", () => {
        if (Number(btn.dataset.answer) === q.answer) {
          score++;
        }

        current++;

        showQuestion();
      });
    });
  };

  showQuestion();
}


function setupIntro() {
  const intro = document.getElementById("intro");
  const btn = document.getElementById("enterBtn");

  document.body.classList.add("no-scroll");

  btn.addEventListener("click", () => {
    intro.classList.add("hide");

    document.body.classList.remove("no-scroll");

    launchConfetti(180);

    setTimeout(() => intro.remove(), 800);
  });
}


function setupMenu() {
  const btn = document.getElementById("menuBtn");
  const nav = document.getElementById("navLinks");

  btn.addEventListener("click", () => {
    nav.classList.toggle("open");
  });

  nav.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => {
      nav.classList.remove("open");
    });
  });
}


function setupModal() {
  document.querySelectorAll("[data-close-modal]").forEach((el) => {
    el.addEventListener("click", closeGift);
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") {
      closeGift();
    }
  });
}


function openGift(index) {
  const gift = CONFIG.gifts[index];

  document.getElementById("giftModalIcon").textContent = gift.icon;
  document.getElementById("giftModalTitle").textContent = gift.title;
  document.getElementById("giftModalText").textContent = gift.text;

  document.getElementById("giftModal").classList.remove("hidden");

  document.body.classList.add("no-scroll");
}


function closeGift() {
  document.getElementById("giftModal").classList.add("hidden");

  document.body.classList.remove("no-scroll");
}


function setupReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          observer.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.12
    }
  );

  document.querySelectorAll(".reveal").forEach((el) => {
    observer.observe(el);
  });
}


