function renderMemories() {
  const root = document.getElementById("memoryGrid");

  CONFIG.memories.forEach((item) => {
    const card = document.createElement("article");

    card.className = "memory-card reveal";

    const title = item.title || "";
    const text = item.text || "";

    const hasCopy = Boolean(title || text);

    // Apply special class only to nightstay.jpeg
    const imageClass = item.image.includes("nightstay.jpeg")
      ? "show-full-image"
      : "";

    card.innerHTML = `
      <img
        src="${item.image}"
        alt="${escapeHtml(title || "Memory")}"
        loading="lazy"
        class="${imageClass}"
      />

      ${
        hasCopy
          ? `
        <div class="memory-copy">
          ${title ? `<h3>${escapeHtml(title)}</h3>` : ""}
          ${text ? `<p>${escapeHtml(text)}</p>` : ""}
        </div>
      `
          : ""
      }
    `;

    root.appendChild(card);
  });
}


function renderGifts() {
  const root = document.getElementById("giftGrid");

  CONFIG.gifts.forEach((gift, index) => {
    const btn = document.createElement("button");

    btn.className = "gift-card reveal";
    btn.dataset.giftIndex = index;

    btn.innerHTML = `
      <div class="gift-icon">${gift.icon}</div>
      <h3>${escapeHtml(gift.title)}</h3>
      <p>${escapeHtml(gift.preview)}</p>
    `;

    btn.addEventListener("click", () => openGift(index));

    root.appendChild(btn);
  });
}


